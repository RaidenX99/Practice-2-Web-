# -*- coding: utf-8 -*-
import random
import math
import hashlib
import json

SECRET_SALT = "Ural_Telecom_2026_Secret"

class PracticeEngine:
    def __init__(self, student_id: str):
        self.student_id = student_id.strip().upper()
        self.seed = self._generate_seed()
        random.seed(self.seed)

    def _generate_seed(self):
        hash_obj = hashlib.md5(self.student_id.encode())
        return int(hash_obj.hexdigest(), 16)

    def generate_variant(self) -> dict:
        rng = random.Random(self.seed)
        pool = []

        # 1. Передача пакетов: ровно k успешных пакетов из n
        n1 = rng.choice([8, 10, 12])
        k1 = rng.randint(4, n1 - 2)
        p1 = 0.8
        ans1 = math.comb(n1, k1) * (p1 ** k1) * ((1 - p1) ** (n1 - k1))
        pool.append({
            'text': f"Канал связи передает пакеты данных с вероятностью успешной доставки $p = {p1}$. Какова вероятность того, что из {n1} отправленных пакетов ровно {k1} дойдут без искажений? (Округление до 4 знаков).",
            'answer': str(round(ans1, 4))
        })

        # 2. Сбои роутера / коммутатора (формула Бернулли)
        n2 = rng.choice([9, 10, 12])
        k2 = rng.randint(2, 4)
        p2 = 0.15 # вероятность сбоя
        ans2 = math.comb(n2, k2) * (p2 ** k2) * ((1 - p2) ** (n2 - k2))
        pool.append({
            'text': f"В серии из {n2} тестовых запросов к сетевому маршрутизатору вероятность сбоя в каждом запросе равна {p2}. Найти вероятность того, что произойдет ровно {k2} сбоя. (Округление до 4 знаков).",
            'answer': str(round(ans2, 4))
        })

        # 3. Атака на сервер / DDoS (успешные блокировки)
        p3 = 0.75
        n3 = 5
        k3 = 4
        ans3 = math.comb(n3, k3) * (p3 ** k3) * ((1 - p3) ** (n3 - k3))
        pool.append({
            'text': f"Система фильтрации трафика (WAF) успешно блокирует вредоносный запрос в {int(p3*100)}% случаев. Какова вероятность того, что из {n3} перехваченных атакующих запросов система отразит ровно {k3}? (Округление до 4 знаков).",
            'answer': str(round(ans3, 4))
        })

        # 4. Всхожесть/доступность микросервисов (не менее половины)
        p4 = 0.8
        n4 = 6
        ans4 = sum(math.comb(n4, k) * (p4**k) * ((1-p4)**(n4-k)) for k in range(3, n4+1))
        pool.append({
            'text': f"Кластер из {n4} микросервисов имеет коэффициент доступности каждого узла 80%. Найти вероятность того, что в произвольный момент времени работоспособны будут не менее половины узлов (от 3 до 6 включительно). (Округление до 4 знаков).",
            'answer': str(round(ans4, 4))
        })

        # 5. Ошибки в коде / баги при компиляции (ровно k из n)
        n5 = 12
        k5 = 3
        p5 = 0.25
        ans5 = math.comb(n5, k5) * (p5 ** k5) * ((1 - p5) ** (n5 - k5))
        pool.append({
            'text': f"При компиляции программного модуля вероятность обнаружения синтаксической ошибки в отдельной функции равна {p5}. Какова вероятность того, что в модуле из {n5} функций будет обнаружено ровно {k5} с ошибками? (Округление до 4 знаков).",
            'answer': str(round(ans5, 4))
        })

        # 6. Отказоустойчивость серверов (больше 8 успешных из 10)
        p6 = 0.6
        n6 = 10
        ans6 = sum(math.comb(n6, k) * (p6**k) * ((1-p6)**(n6-k)) for k in range(9, 11))
        pool.append({
            'text': f"Вероятность успешной обработки транзакции сервером составляет 0.6. Какова вероятность того, что в серии из {n6} транзакций успешными окажутся больше 8 (9 или 10)? (Округление до 4 знаков).",
            'answer': str(round(ans6, 4))
        })

        # 7. Надежность VPN-соединения (ни одного обрыва из 3 сессий)
        p7 = 0.7
        n7 = 3
        ans7 = math.comb(n7, 3) * (p7**3)
        pool.append({
            'text': f"Туннель VPN удерживает стабильное соединение с вероятностью 0.7 за сеанс. Найти вероятность того, что из трех последовательных сеансов не будет потеряно ни одного (все 3 пройдут стабильно). (Округление до 4 знаков).",
            'answer': str(round(ans7, 4))
        })

        # 8. Искажение пакетов (ровно 3 из 10)
        p8 = 0.1
        n8 = 10
        k8 = 3
        ans8 = math.comb(n8, k8) * (p8**k8) * ((1-p8)**(n8-k8))
        pool.append({
            'text': f"При передаче данных по беспроводному каналу Wi-Fi вероятность искажения кадра равна 0.1. Какова вероятность того, что блок из 10 кадров содержит ровно 3 искаженных? (Округление до 4 знаков).",
            'answer': str(round(ans8, 4))
        })

        # 9. Искажение пакетов (0 искажений из 10)
        ans9 = math.comb(10, 0) * (0.9**10)
        pool.append({
            'text': f"Вероятность искажения кадра в канале равна 0.1. Какова вероятность того, что пакет из 10 переданных кадров не содержит искаженных кадров вообще? (Округление до 4 знаков).",
            'answer': str(round(ans9, 4))
        })

        # 10. Потеря пакетов по протоколу UDP (принцип обратного события: хотя бы 2 потери из 20)
        p10 = 0.05
        n10 = 20
        p_less_2 = math.comb(n10, 0)*(0.95**20) + math.comb(n10, 1)*0.05*(0.95**19)
        ans10 = 1 - p_less_2
        pool.append({
            'text': f"Вероятность потери UDP-пакета на узле маршрутизации равна 0.05. Какова вероятность потерять хотя бы пару пакетов (2 и более) при отправке потока из 20 пакетов? (Округление до 4 знаков).",
            'answer': str(round(ans10, 4))
        })

        # 11. Авторизация по токену / капча (как тест с вариантами)
        p_fail = math.comb(11, 0)*(0.75**11) + math.comb(11, 1)*(0.25)*(0.75**10)
        ans11 = 1 - p_fail
        pool.append({
            'text': f"Скрипт автоматического подбора пароля перебирает 11 полей, в каждом из которых 4 возможных символа (угадывание наугад с вероятностью 1/4). Для успешного взлома боту достаточно угадать не менее чем 2 символа. Найти вероятность успешного подбора для случайного угадывания. (Округление до 4 знаков).",
            'answer': str(round(ans11, 4))
        })

        # 12. Попадание пакетов в буфер (не менее 3 раз из 10 при p=1/6)
        p_less_3 = sum(math.comb(10, k) * ((1/6)**k) * ((5/6)**(10-k)) for k in range(3))
        ans12 = 1 - p_less_3
        pool.append({
            'text': f"В буфер обмена сетевого адаптера поступают кадры. Вероятность переполнения буфера в одном такте равна 1/6. Какова вероятность того, что за 10 тактов переполнение случится не менее 3 раз? (Округление до 4 знаков).",
            'answer': str(round(ans12, 4))
        })

        # 13. Тестирование API (из 8 запросов больше половины успешных, p=0.7)
        p13 = 0.7
        n13 = 8
        ans13 = sum(math.comb(n13, k) * (p13**k) * ((1-p13)**(n13-k)) for k in range(5, 9))
        pool.append({
            'text': f"Интеграционный API возвращает успешный код ответа в 70% вызовов. Найти вероятность того, что в серии из 8 тестовых запросов успешными будут больше половины (от 5 до 8 запросов включительно). (Округление до 4 знаков).",
            'answer': str(round(ans13, 4))
        })

        # 14. Сравнение пропускной способности двух каналов (Матч из 3 сессий, p=1/3)
        p14 = 1/3
        ans14 = math.comb(3, 2)*(p14**2)*(2/3) + math.comb(3, 3)*(p14**3)
        pool.append({
            'text': f"Резервный канал связи передает данные в 2 раза медленнее основного (вероятность успешной передачи пакета в словом тайм-слоте равна 1/3). Какова вероятность успешно передать пакет без коллизий в сеансе из 3 тайм-слотов, если для успеха нужно передать не менее 2 пакетов? (Округление до 4 знаков).",
            'answer': str(round(ans14, 4))
        })

        # 15. Сеанс из 5 тайм-слотов (выиграть >= 3)
        p15 = 1/3
        ans15 = sum(math.comb(5, k) * (p15**k) * ((2/3)**(5-k)) for k in range(3, 6))
        pool.append({
            'text': f"Вероятность успешной передачи пакета в тайм-слоте равна 1/3. Какова вероятность успешной передачи в сеансе из 5 тайм-слотов, если требуется минимум 3 успешных слота? (Округление до 4 знаков).",
            'answer': str(round(ans15, 4))
        })

        # 16. Брутфорс пин-кода (9 успешных совпадений из 10 при p=0.5)
        ans16 = math.comb(10, 9) * (0.5**10)
        pool.append({
            'text': f"Сетевой сканер угадывает двоичный бит ответа узла (0 или 1) с вероятностью 0.5. Какова вероятность угадать верный ответ ровно в 9 случаях из 10 попыток? (Округление до 4 знаков).",
            'answer': str(round(ans16, 4))
        })

        # 17. Брутфорс (3 из 4 попыток)
        ans17 = math.comb(4, 3) * (0.5**4)
        pool.append({
            'text': f"Сканер угадывает двоичный бит ответа узла с вероятностью 0.5. Какова вероятность угадать ровно 3 раза из 4 попыток? (Округление до 4 знаков).",
            'answer': str(round(ans17, 4))
        })

        # 18. Совпадение кодов ошибок у двух независимых модулей мониторинга (по 2 проверки)
        pool.append({
            'text': f"Два независимых модуля мониторинга отправляют по 2 тестовых эхо-запроса (вероятность успешного отхода равна 1/6). Какова вероятность того, что количество успешных эхо-ответов у обоих модулей совпадет? (Округление до 4 знаков).",
            'answer': "0.5602"
        })

        # 19. Передача байта данных (бит может прийти с ошибкой, p=0.5, ровно 5 единиц из 10)
        ans19 = math.comb(10, 5) * (0.5**10)
        pool.append({
            'text': f"При передаче байта симметричный канал искажает биты с равной вероятностью 0.5. Какова вероятность того, что в пакете из 10 бит окажется ровно 5 единичных бит? (Округление до 4 знаков).",
            'answer': str(round(ans19, 4))
        })

        # 20. Контроль доступа: из 25 подключений не пройдут авторизацию более трех (p_ошибки = 0.4)
        p_fail_8 = 0.4
        n_8 = 25
        p_le_3 = sum(math.comb(n_8, k) * (p_fail_8**k) * ((1 - p_fail_8)**(n_8 - k)) for k in range(4))
        ans20 = 1 - p_le_3
        pool.append({
            'text': f"Вероятность того, что подключение к серверу завершится ошибкой авторизации, равна 0.4. Определить вероятность того, что в группе из 25 подключений ошибки авторизации произойдут более чем у трех клиентов (т.е. сбоев будет от 4 до 25). (Округление до 4 знаков).",
            'answer': str(round(ans20, 4))
        })

        rng.shuffle(pool)

        variant = {}
        for idx, task_item in enumerate(pool):
            task_num = idx + 1
            variant[f"task_{task_num}"] = task_item

        cq_pool = [
            "Сформулируйте определение схемы Бернулли в контексте передачи дискретных сообщений и запишите формулу для вычисления вероятности $P_n(k)$.",
            "В чем заключается принцип обратного события и почему он важен при расчете надежности пакетов данных в схеме Бернулли?",
            "Как вычисляется вероятность того, что число успешных доставок пакетов в схеме Бернулли лежит в заданном интервале от $k_1$ до $k_2$?"
        ]
        variant['task_99'] = {
            'title': 'Контрольный теоретический вопрос',
            'text': f"ОБЯЗАТЕЛЬНО прикрепите фото с развернутым рукописным ответом на вопрос:\n\n{rng.choice(cq_pool)}",
            'answer': 'Ручная проверка (Требуется фото)'
        }
        
        return variant

    @staticmethod
    def generate_security_hash(student_id: str, student_answers: dict) -> str:
        answers_str = json.dumps(student_answers, sort_keys=True)
        raw_data = f"{student_id}_{answers_str}_{SECRET_SALT}"
        return hashlib.sha256(raw_data.encode('utf-8')).hexdigest()

    def check_answers(self, student_answers: dict) -> dict:
        variant = self.generate_variant()
        correct_count = 0
        total_count = len(variant)
        details = {}

        def is_close(val1, val2, tol=0.01):
            try:
                return abs(float(val1) - float(val2)) <= tol
            except ValueError:
                return str(val1).strip().lower() == str(val2).strip().lower()

        for task_key, task_data in variant.items():
            photo_list = student_answers.get(f"{task_key}_photo", [])
            has_photo = bool(photo_list)
            
            student_ans_str = student_answers.get(task_key, "").strip().replace(',', '.')
            correct_ans_str = str(task_data.get('answer', ''))
            
            if task_key == 'task_99':
                if has_photo:
                    is_correct = True
                    correct_count += 1
                    details[task_key] = {'is_correct': True, 'correct_answer': "Фото прикреплено", 'student_answer': f"Фото ({len(photo_list)} шт.)"}
                else:
                    details[task_key] = {'is_correct': False, 'correct_answer': "Требуется фото", 'student_answer': "Нет фото!"}
                continue

            is_correct = is_close(student_ans_str, correct_ans_str)
            if not has_photo:
                is_correct = False
                student_ans_str = f"{student_ans_str} (Нет фото!)" if student_ans_str else "Нет ответа (Нет фото!)"

            if is_correct: correct_count += 1
            details[task_key] = {'is_correct': is_correct, 'correct_answer': correct_ans_str, 'student_answer': student_ans_str}

        score_percent = (correct_count / total_count) * 100
        if score_percent >= 85: mark = 5
        elif score_percent >= 70: mark = 4
        elif score_percent >= 50: mark = 3
        else: mark = 2

        photos_dict = {k: student_answers.get(f"{k}_photo") for k in variant.keys() if student_answers.get(f"{k}_photo")}

        return {
            'correct_count': correct_count,
            'total_count': total_count,
            'percent': round(score_percent, 1),
            'mark': mark,
            'details': details,
            'photos': photos_dict
        }
